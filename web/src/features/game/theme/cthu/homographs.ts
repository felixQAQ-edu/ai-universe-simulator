//   ③ **替换后不荒诞**:换掉之后那一句仍像一句人写的话,只是**微妙地不对**;
//   ④ **不依赖特定字体才相似**:宋体、黑体、系统默认下都该近似 —— 只在某一种字体下才像的
//      (靠特定字形的连笔/出头)不收,因为真机字体与桌面不同(这正是 swap 型的命门)。
//
// ── 方向性 ────────────────────────────────────────────────────────────
// 表是**单向**的(原字 → 替身)。刻意不做「自动双向」:双向要求两个方向都满足条件 ③,
// 而这需要逐条再判一遍(「土→士」通顺不代表「士→土」在任何句子里都通顺)。
